"use client";

import { useCallback, useEffect, useRef, useState } from "react";

interface Msg {
  direction: string;
  sender: string;
  body: string;
  created_at: string;
  whatsapp_message_id: string | null;
  handled_by: string | null;
  generated_by: string | null;
}

interface Turn {
  message_id: string | null;
  layer: string;
  matched: string | null;
  step: string | null;
  next_step: string | null;
  total_ms: number;
  db_ms: number;
  llm_calls: number;
  parsed: Record<string, unknown> | null;
  unrecognised: boolean;
}

export default function Simulator() {
  const [phone, setPhone] = useState("+23057000001");
  const [text, setText] = useState("");
  const [msgs, setMsgs] = useState<Msg[]>([]);
  const [turns, setTurns] = useState<Turn[]>([]);
  const [uploadLink, setUploadLink] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const end = useRef<HTMLDivElement>(null);

  const load = useCallback(async () => {
    const res = await fetch(
      `/api/dev/simulator?phone=${encodeURIComponent(phone)}`,
    );
    if (!res.ok) return;
    const j = await res.json();
    setMsgs(j.messages ?? []);
    setTurns(j.turns ?? []);
    setUploadLink(j.uploadLink ?? null);
  }, [phone]);

  useEffect(() => {
    const t = setTimeout(() => void load(), 0);
    const poll = setInterval(() => void load(), 5000);
    return () => {
      clearTimeout(t);
      clearInterval(poll);
    };
  }, [load]);
  useEffect(() => {
    end.current?.scrollIntoView();
  }, [msgs]);

  async function send(payload: { text?: string; replyId?: string }) {
    setBusy(true);
    setError(null);
    const res = await fetch("/api/dev/simulator", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ phone, ...payload }),
    });
    if (!res.ok) setError(`Bot call failed (${res.status})`);
    setText("");
    await load();
    setBusy(false);
  }

  const buttons = [
    "menu:view_cars",
    "menu:check_availability",
    "menu:existing_booking",
    "menu:talk_human",
    "menu:main",
    "nav:back",
    "confirm:yes",
    "confirm:change",
    "confirm:cancel",
    "loc:same",
  ];

  return (
    <main className="mx-auto max-w-lg p-4">
      <h1 className="mb-1 text-lg font-semibold">WhatsApp simulator</h1>
      <p className="mb-3 text-xs text-zinc-500">
        Chat with the bot as a fake number — no Meta needed. Replies are shown
        from the stored thread.
      </p>
      <input
        value={phone}
        onChange={(e) => setPhone(e.target.value)}
        className="mb-2 w-full rounded border p-2 text-sm"
      />
      <div className="mb-2 flex h-96 flex-col gap-2 overflow-y-auto rounded bg-zinc-100 p-3">
        {msgs.map((m, i) => (
          <div
            key={i}
            className={`max-w-[85%] rounded-lg p-2 text-sm whitespace-pre-wrap ${m.direction === "INBOUND" ? "self-end bg-green-100" : "self-start bg-white"}`}
          >
            {m.body}
            {m.direction === "INBOUND" &&
              (() => {
                const t = turns.find(
                  (x) => x.message_id === m.whatsapp_message_id,
                );
                return t ? (
                  <div className="mt-1 border-t border-green-300 pt-1 font-mono text-[10px] text-zinc-600">
                    <b>{t.layer}</b> · {t.matched ?? "—"} · {t.step} →{" "}
                    {t.next_step} · {t.total_ms} ms (db {t.db_ms}) · llm calls{" "}
                    {t.llm_calls}
                    {t.unrecognised && " · NOT UNDERSTOOD"}
                    {t.parsed && (
                      <pre className="whitespace-pre-wrap">
                        {JSON.stringify(t.parsed, null, 1)}
                      </pre>
                    )}
                  </div>
                ) : null;
              })()}
            {m.generated_by === "llm" && (
              <div className="mt-1 text-[10px] text-purple-700 uppercase">
                generated by llm
              </div>
            )}
          </div>
        ))}
        <div ref={end} />
      </div>
      {uploadLink && (
        <p className="mb-2 text-sm">
          Document upload link:{" "}
          <a className="underline" href={uploadLink} target="_blank">
            {uploadLink}
          </a>
        </p>
      )}
      <div className="mb-2 flex flex-wrap gap-1">
        {buttons.map((b) => (
          <button
            key={b}
            disabled={busy}
            onClick={() => send({ replyId: b })}
            className="rounded-full border px-2 py-1 text-xs"
          >
            {b}
          </button>
        ))}
      </div>
      <form
        onSubmit={(e) => {
          e.preventDefault();
          if (text.trim()) void send({ text });
        }}
        className="flex gap-2"
      >
        <input
          value={text}
          onChange={(e) => setText(e.target.value)}
          placeholder="Type a message…"
          className="flex-1 rounded border p-2 text-sm"
        />
        <button disabled={busy} className="rounded bg-black px-3 text-white">
          {busy ? "…" : "Send"}
        </button>
      </form>
      {error && <p className="mt-2 text-sm text-red-700">{error}</p>}
    </main>
  );
}
